/** Level → its rows, in syllabus order. */
const LEVELS: [1 | 2 | 3, Row[]][] = [
  [1, L1],
  [2, L2],
  [3, L3],
];

export const HSK123_COUNT = L1.length + L2.length + L3.length;

const batchName = (level: number, i: number): string =>
  `HSK${level} · Đợt ${String(i + 1).padStart(2, '0')}`;

export interface Hsk123Split {
  fresh: Vocab[];
  topics: string[];
  /** Batch topics for levels 1–2, which start switched off. */
  offByDefault: string[];
  known: Map<string, Omit<Vocab, 't'>>;
}

/**
 * Splits the list against words the deck already carries, numbering batches per level
 * after the split so each one is full.
 *
 * Levels 1 and 2 come back in `offByDefault`: they are here for completeness of the
 * 1200-word syllabus, not because someone sitting HSK 4 needs to be taught 我 and 好.
 * Letting them into the rotation by default would spend the daily new-word budget on
 * words the user already knows — the most expensive kind of busywork an SRS can create.
 */
export function splitHsk123(existing: Set<string>): Hsk123Split {
  const fresh: Vocab[] = [];
  const topics: string[] = [];
  const offByDefault: string[] = [];
  const known = new Map<string, Omit<Vocab, 't'>>();

  for (const [level, rows] of LEVELS) {
    let n = 0;
    for (const [h, p, pos, m, ex, exVi] of rows) {
      if (existing.has(h)) {
        known.set(h, { h, p, pos, m, ex, exVi });
        continue;
      }
      fresh.push({ h, p, pos, m, ex, exVi, t: batchName(level, Math.floor(n / HSK123_BATCH)) });
      n++;
    }
    const batches = Array.from({ length: Math.ceil(n / HSK123_BATCH) }, (_, i) => batchName(level, i));
    topics.push(...batches);
    if (level !== 3) offByDefault.push(...batches);
  }

  return { fresh, topics, offByDefault, known };
}
