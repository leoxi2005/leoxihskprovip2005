/** Every word on the list, before any deduplication against the existing deck. */
export const HSK4_ALL: Omit<Vocab, 't'>[] = ROWS.map(([h, p, pos, m, ex, exVi]) => ({
  h,
  p,
  pos,
  m,
  ex,
  exVi,
}));

export const HSK4_COUNT = HSK4_ALL.length;

const batchName = (i: number): string => `HSK4 · Đợt ${String(i + 1).padStart(2, '0')}`;

export interface Hsk4Split {
  /** Words not already in the deck, tagged with an even batch topic. */
  fresh: Vocab[];
  /** Batch topic names, in order. */
  topics: string[];
  /** Words the deck already had, keyed by hanzi — used to fill in missing examples. */
  known: Map<string, Omit<Vocab, 't'>>;
}

/**
 * Splits the list against words the deck already carries.
 *
 * Batches are numbered *after* the split, not before, so every batch holds a full 30
 * words to learn. Numbering first would leave "Đợt 01" with whatever handful happened
 * not to overlap — a study plan built on that would be lumpy for no reason.
 */
export function splitHsk4(existing: Set<string>): Hsk4Split {
  const fresh: Vocab[] = [];
  const known = new Map<string, Omit<Vocab, 't'>>();

  for (const w of HSK4_ALL) {
    if (existing.has(w.h)) known.set(w.h, w);
    else fresh.push({ ...w, t: batchName(Math.floor(fresh.length / HSK4_BATCH)) });
  }

  const topics = Array.from({ length: Math.ceil(fresh.length / HSK4_BATCH) }, (_, i) => batchName(i));
  return { fresh, topics, known };
}
